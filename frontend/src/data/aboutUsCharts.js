const massPresentationRanges = Object.freeze([
  [0, 100],
  [100, 200],
  [200, 300],
  [300, 400],
  [400, 500],
  [500, 600],
  [600, 700],
  [700, 800],
  [800, 900],
  [900, 1100],
  [1100, 1500],
])
const massPresentationBins = Object.freeze(
  massPresentationRanges.map(([lower, upper]) =>
    Object.freeze({
      lower,
      upper,
      count: massDistribution.bins
        .filter((bin) => bin.lower >= lower && bin.upper <= upper)
        .reduce((sum, bin) => sum + bin.count, 0),
    }),
  ),
)

